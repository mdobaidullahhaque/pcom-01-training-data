"""Generate schema/schema.sql. Stops without writing if the column count is wrong."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import config

TABLE_NAME = "pcom01_training"
EXPECTED_COLUMNS = 225  # 224 PCOM-01 core columns + prediction_date

MONTHS = [f"M{i}" for i in range(config.FEATURE_MONTHS)]
GHSA_COUNTS = [f"ghsa_{severity}_count" for severity in config.SEVERITIES]
DAYS_OBSERVED = "package_download_days_observed"
MONTHLY_FAMILIES = [
    "package_downloads",
    DAYS_OBSERVED,
    "package_stable_release_count",
    "issues_opened",
    "issues_closed",
    "issues_reopened",
    "pull_requests_opened",
    "pull_requests_closed_unmerged",
    "pull_requests_merged",
    "pull_requests_reopened",
    "issues_open_at_month_end",
    "pull_requests_open_at_month_end",
]


def count_column(name, required=True, check=None):
    check = check or f"{name} >= 0"
    not_null = " NOT NULL" if required else ""
    return f"{name} INTEGER{not_null} CHECK ({check})"


def monthly_columns(family, required):
    for month in MONTHS:
        name = f"{family}_{month}"
        check = f"{name} BETWEEN 0 AND 31" if family == DAYS_OBSERVED else None
        yield count_column(name, required, check)


def build_columns():
    # Metadata
    columns = [
        "purl TEXT NOT NULL CHECK (length(purl) <= 2048) CHECK (purl LIKE 'pkg:npm/%')",
        "package_created_at TEXT NOT NULL",
        "published_at TEXT NOT NULL",
    ]
    # General
    columns += [count_column(name, required=False) for name in ("unpacked_size", "file_count")]
    columns += [
        count_column(name)
        for name in (
            "dependency_count",
            "optional_dependency_count",
            "peer_dependency_count",
            "dev_dependency_count",
            "bundled_dependency_count",
        )
    ]
    # Monthly series
    for family in MONTHLY_FAMILIES:
        columns += monthly_columns(family, required=False)
    # GHSA general
    columns += [count_column(name) for name in GHSA_COUNTS]
    # GHSA monthly
    for family in GHSA_COUNTS:
        columns += monthly_columns(family, required=True)
    # Targets
    columns += [count_column(f"target_{name}_90d") for name in GHSA_COUNTS]
    # Extra column, not part of the PCOM-01 core
    columns.append("prediction_date TEXT NOT NULL")
    return columns


def main():
    columns = build_columns()
    print(f"Column count: {len(columns)} (expected {EXPECTED_COLUMNS})")
    if len(columns) != EXPECTED_COLUMNS:
        sys.exit("Column count mismatch; schema.sql not written.")

    lines = [
        "-- PCOM-01 training dataset. Generated by scripts/generate_schema.py; do not edit by hand.",
        "-- One row = one npm package version (purl) at one prediction date.",
        f"CREATE TABLE {TABLE_NAME} (",
    ]
    lines += [f"    {column}," for column in columns]
    lines += ["    UNIQUE (purl, prediction_date)", ");"]
    config.SCHEMA_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {config.SCHEMA_PATH}")


if __name__ == "__main__":
    main()
